export const levelPath = (level, language) => language === 'tr'
  ? `/konular/almanca-${level.toLowerCase()}/`
  : `/en/german-${level.toLowerCase()}/`;

export const grammarPath = language => language === 'tr' ? '/konular/almanca-gramer/' : '/en/german-grammar/';
export const readerPath = language => language === 'tr' ? '/konular/mini-paketler/' : '/en/mini-packs/';
export const lessonTitle = (pack, language) => `${pack.title} · ${language === 'tr' ? 'Almanca' : 'German'} ${pack.cefr} · Baulingo`;
export const grammarPaths = ['tr', 'en'].map(grammarPath);
export const grammarLesson = id => id.includes('-G');

export function lessonPath(id, language) {
  if (!Object.hasOwn(slugs, id)) return null;
  const level = id.slice(3, 5);
  const base = grammarLesson(id) ? `${grammarPath(language)}${level.toLowerCase()}/` : levelPath(level, language);
  return `${base}${slugs[id][language]}/`;
}

export const turkishLessonPath = id => lessonPath(id, 'tr');
export const lessonPaths = Object.keys(slugs).flatMap(id => [lessonPath(id, 'tr'), lessonPath(id, 'en')]);
